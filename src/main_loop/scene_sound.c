struct SceneVolume
{
    /*0x00*/ int track;
    /*0x04*/ u8 volume;
    /*0x08*/ int scene;
    /*0x0C*/ int frame;
    /*0x10*/ u32 time;
};  /* size = 0x14 */

struct SceneGroup
{
    /*0x00*/ int id;
    /*0x04*/ u8 volume;
    /*0x05*/ u8 pan;
    /*0x06*/ u8 span;
    /*0x07*/ s8 state;
    /*0x08*/ int startScene;
    /*0x0C*/ int startFrame;
    /*0x10*/ int endScene;
    /*0x14*/ int endFrame;
    /*0x18*/ int key;
    /*0x1C*/ s8 preloaded;
};  /* size = 0x20 */

struct SceneFade
{
    /*0x00*/ int mode;
    /*0x04*/ int id;
    /*0x08*/ int scene;
    /*0x0C*/ int frame;
    /*0x10*/ int step;
    /*0x14*/ int volume;
    /*0x18*/ int target;
    /*0x1C*/ s8 active;
    /*0x20*/ int key;
};  /* size = 0x24 */

struct SceneCue
{
    /*0x00*/ int id;
    /*0x04*/ int unk4;
    /*0x08*/ int unk8;
    /*0x0C*/ u32 unkC;
    /*0x10*/ u32 unk10;
};  /* size = 0x14 */

